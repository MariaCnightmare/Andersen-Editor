const STORAGE_KEY = "ae:lang";
let languageChoice = null;
let lastAppliedLanguage = null;

function readStoredLanguageChoice() {
  if (languageChoice) return languageChoice;
  try {
    languageChoice = localStorage.getItem(STORAGE_KEY) || "system";
  } catch {
    languageChoice = "system";
  }
  return languageChoice;
}

export function resolveLanguageChoice(choice) {
  const c = String(choice || "system").toLowerCase();
  if (c === "ja" || c === "en") return c;
  const nav = typeof navigator !== "undefined" ? navigator : null;
  const langs = [nav?.language, ...(nav?.languages || [])].map((x) => String(x || "").toLowerCase());
  return langs.some((x) => x.startsWith("ja")) ? "ja" : "en";
}

export function setLanguage(choice) {
  const normalized = (choice === "ja" || choice === "en") ? choice : "system";
  languageChoice = normalized;
  try {
    localStorage.setItem(STORAGE_KEY, normalized);
  } catch {}
  return resolveLanguageChoice(normalized);
}

export function t(key, vars = {}) {
  const pref = readStoredLanguageChoice();
  const lang = resolveLanguageChoice(pref);
  const table = I18N[lang] || I18N.en;
  let out = table[key];
  if (typeof out !== "string") out = I18N.en[key];
  if (typeof out !== "string") out = String(key);
  for (const [k, v] of Object.entries(vars)) {
    out = out.replaceAll(`{${k}}`, String(v));
  }
  return out;
}

